REFERENCES_ALLOWED: dict[str, set[str]] = {
    ".gitignore": {"pipelines/orders-learning"},
    "scripts/tests/test_actions_infra.py": {"deploy-progressive.yml"},
}


def test_nothing_points_at_a_retired_path():
    dangling = {}
    for name in repository_files():
        if not scannable(name):
            continue
        try:
            text = (ROOT / name).read_text(encoding="utf-8").replace("\\", "/")
        except UnicodeDecodeError:
            continue
        found = {reference for reference in RETIRED_REFERENCES if reference in text}
        found -= next((tokens for pattern, tokens in REFERENCES_ALLOWED.items() if fnmatch.fnmatch(name, pattern)), set())
        if found:
            dangling[name] = sorted(found)
    assert not dangling, "references to deleted or renamed files:\n" + "\n".join(
        f"  {name}: {', '.join(references)}" for name, references in sorted(dangling.items()))
