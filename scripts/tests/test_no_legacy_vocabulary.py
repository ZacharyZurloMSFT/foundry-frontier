def repository_files() -> list[str]:
    try:
        listing = subprocess.run(["git", "ls-files", "-co", "--exclude-standard", "-z"], cwd=ROOT,
                                 capture_output=True, check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        pytest.skip("not a git checkout")
    return [name for name in listing.decode("utf-8").split("\0") if name and (ROOT / name).is_file()]


def scannable(name: str) -> bool:
    if Path(name).suffix.lower() in BINARY or any(fnmatch.fnmatch(name, pattern) for pattern in EXEMPT):
        return False
    return (ROOT / name).stat().st_size <= 2_000_000


def hits() -> dict[str, set[str]]:
    found: dict[str, set[str]] = {}
    for name in repository_files():
        if not scannable(name):
            continue
        try:
            text = (ROOT / name).read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        tokens = {token for token, pattern in LEXICON.items() if pattern.search(text)}
        if tokens:
            found[name] = tokens
    return found


def allowed_tokens(name: str) -> set[str]:
    return set().union(*(tokens for pattern, tokens in ALLOWED.items() if fnmatch.fnmatch(name, pattern)))


def test_retired_vocabulary_only_appears_where_it_is_allowed():
    unexpected = {name: sorted(tokens - allowed_tokens(name)) for name, tokens in hits().items()
                  if tokens - allowed_tokens(name)}
    assert not unexpected, "retired retail / orders / field-service / HR-IT vocabulary found:\n" + "\n".join(
        f"  {name}: {', '.join(tokens)}" for name, tokens in sorted(unexpected.items()))


def test_allow_list_has_no_stale_entries():
    found = hits()
    stale = []
    for pattern, tokens in ALLOWED.items():
        matched = {token for name, present in found.items() if fnmatch.fnmatch(name, pattern) for token in present}
        if tokens - matched:
            stale.append(f"{pattern}: {', '.join(sorted(tokens - matched))}")
    assert not stale, "remove these allow-list entries, the vocabulary is gone:\n  " + "\n  ".join(stale)


def test_retired_paths_stay_deleted():
    present = repository_files()
    back = [name for name in present
            for retired in RETIRED_PATHS if name == retired or name.startswith(retired + "/")]
    assert not back, "retired paths are back: " + ", ".join(sorted(back))


