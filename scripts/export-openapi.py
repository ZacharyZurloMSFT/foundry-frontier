"""Export the Northwind API OpenAPI document that is imported into API Management.

The committed spec is the single source for every `*-api` definition in
infra/live/apim-apis.bicep (both Container App stacks serve the same document).
It is written as compact, key-sorted JSON because Bicep's loadTextContent()
rejects files over 131,072 characters. --check is the strict byte comparison
(run it before opening a PR); CI compares the gateway-visible API surface and
the operations table, because schema rendering can vary with library releases.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC_DIR = ROOT / "infra" / "live" / "apim" / "specs"
SPEC = SPEC_DIR / "northwind-api.openapi.json"
TABLE = SPEC_DIR / "northwind-api.operations.md"
METHODS = ("get", "post", "put", "patch", "delete", "head", "options")
BICEP_TEXT_LIMIT = 131072
APIM_OPERATION_NAME_LIMIT = 80


def load_app():
    sys.path.insert(0, str(ROOT))
    os.environ.setdefault("APPLICATIONINSIGHTS_CONNECTION_STRING", "")
    from apps.api.app.main import app

    return app


def render_spec(document: dict) -> str:
    return json.dumps(document, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n"


def operations(document: dict) -> list[dict]:
    rows = []
    for path, item in document["paths"].items():
        for method, operation in item.items():
            if method in METHODS:
                rows.append({
                    "method": method.upper(),
                    "path": path,
                    "operation_id": operation["operationId"],
                    "group": (operation.get("tags") or ["core"])[0],
                })
    return sorted(rows, key=lambda row: (row["path"], row["method"]))


def render_table(document: dict) -> str:
    rows = operations(document)
    lines = [
        "# Northwind API operations imported into API Management",
        "",
        "Generated by `python scripts/export-openapi.py`; do not edit by hand.",
        f"{len(rows)} HTTP operations. The Voice Live WebSocket (`/voice/realtime`) is not part of OpenAPI and is",
        "published as a separate APIM WebSocket API. Paths under `/api/v1` require an Entra delegated token.",
        "",
        "| Method | Path | Operation ID | Group |",
        "| --- | --- | --- | --- |",
    ]
    lines += [f"| {r['method']} | `{r['path']}` | `{r['operation_id']}` | {r['group']} |" for r in rows]
    return "\n".join(lines) + "\n"


def generated() -> dict[Path, str]:
    document = load_app().openapi()
    return {SPEC: render_spec(document), TABLE: render_table(document)}


def read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed files are stale")
    args = parser.parse_args()
    outputs = generated()
    if len(outputs[SPEC]) > BICEP_TEXT_LIMIT:
        print(f"Spec exceeds Bicep loadTextContent limit ({len(outputs[SPEC])} > {BICEP_TEXT_LIMIT}).", file=sys.stderr)
        return 1
    stale = [path for path, text in outputs.items() if read(path) != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python scripts/export-openapi.py)", file=sys.stderr)
        return 1 if stale else 0
    SPEC_DIR.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
