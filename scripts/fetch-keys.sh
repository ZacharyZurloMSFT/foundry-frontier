#!/usr/bin/env bash
# Fetch admin/API keys for Foundry, Cosmos, Storage, Search into .env
# Usage: ./scripts/fetch-keys.sh [resource-group]
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="${REPO_ROOT}/.env"
RG="${1:-${AZURE_RESOURCE_GROUP:-}}"

# Read azd env
declare -A AZD
while IFS= read -r line; do
  if [[ "$line" =~ ^([A-Z_][A-Z0-9_]*)=\"?([^\"]*)\"?$ ]]; then
    AZD["${BASH_REMATCH[1]}"]="${BASH_REMATCH[2]}"
  fi
done < <(azd env get-values 2>/dev/null || true)

if [[ -z "$RG" ]]; then RG="${AZD[AZURE_RESOURCE_GROUP]:-}"; fi
if [[ -z "$RG" ]]; then
  echo "ERROR: pass resource group as \$1 or set AZURE_RESOURCE_GROUP." >&2
  exit 1
fi

echo "==> Fetching keys from '$RG' into '$ENV_FILE'"

declare -A KEYS

while IFS=$'\t' read -r TYPE NAME; do
  case "$TYPE" in
    Microsoft.CognitiveServices/accounts)
      echo "→ Foundry / AI Services: $NAME"
      KEYS[FOUNDRY_API_KEY]="$(az cognitiveservices account keys list -g "$RG" -n "$NAME" --query key1 -o tsv)"
      ;;
    Microsoft.DocumentDB/databaseAccounts)
      echo "→ Cosmos: $NAME"
      KEYS[COSMOS_KEY]="$(az cosmosdb keys list -g "$RG" -n "$NAME" --query primaryMasterKey -o tsv)"
      ;;
    Microsoft.Storage/storageAccounts)
      echo "→ Storage: $NAME"
      KEY="$(az storage account keys list -g "$RG" -n "$NAME" --query '[0].value' -o tsv)"
      KEYS[STORAGE_KEY]="$KEY"
      KEYS[STORAGE_CONNECTION_STRING]="DefaultEndpointsProtocol=https;AccountName=${NAME};AccountKey=${KEY};EndpointSuffix=core.windows.net"
      ;;
    Microsoft.Search/searchServices)
      echo "→ Search: $NAME"
      KEYS[AZURE_SEARCH_KEY]="$(az search admin-key show -g "$RG" --service-name "$NAME" --query primaryKey -o tsv)"
      ;;
  esac
done < <(az resource list -g "$RG" \
  --query "[?type=='Microsoft.CognitiveServices/accounts' || type=='Microsoft.DocumentDB/databaseAccounts' || type=='Microsoft.Storage/storageAccounts' || type=='Microsoft.Search/searchServices'].[type,name]" \
  -o tsv)

MIRROR=(AZURE_RESOURCE_GROUP AZURE_TENANT_ID FOUNDRY_ENDPOINT FOUNDRY_PROJECT_ENDPOINT FOUNDRY_PLANNER_DEPLOYMENT FOUNDRY_WORKER_DEPLOYMENT FOUNDRY_PROMPT_AGENT_DEPLOYMENT AZURE_SEARCH_ENDPOINT AZURE_SEARCH_INDEX AZURE_SEARCH_KNOWLEDGE_BASE AZURE_SEARCH_KNOWLEDGE_SOURCE AZURE_OPENAI_ENDPOINT COSMOS_ENDPOINT COSMOS_DATABASE STORAGE_ACCOUNT STORAGE_CU_CONTAINER STORAGE_SEED_CONTAINER APPLICATIONINSIGHTS_CONNECTION_STRING)
for k in "${MIRROR[@]}"; do
  if [[ -n "${AZD[$k]:-}" ]]; then KEYS[$k]="${AZD[$k]}"; fi
done

declare -A EXISTING
if [[ -f "$ENV_FILE" ]]; then
  while IFS= read -r line; do
    [[ "$line" =~ ^\s*# ]] && continue
    if [[ "$line" =~ ^([A-Z_][A-Z0-9_]*)=(.*)$ ]]; then
      EXISTING["${BASH_REMATCH[1]}"]="${BASH_REMATCH[2]}"
    fi
  done < "$ENV_FILE"
fi
for k in "${!KEYS[@]}"; do EXISTING[$k]="${KEYS[$k]}"; done

{
  echo "# Generated by scripts/fetch-keys.sh — do not commit."
  echo "# Source resource group: $RG"
  echo "# Regenerated: $(date -u +'%Y-%m-%d %H:%M:%SZ')"
  echo ""
  for k in $(echo "${!EXISTING[@]}" | tr ' ' '\n' | sort); do
    echo "${k}=${EXISTING[$k]}"
  done
} > "$ENV_FILE"

echo ""
echo "==> Wrote ${#EXISTING[@]} entries to $ENV_FILE"
echo "    (this file is git-ignored — do not commit)"
