#!/usr/bin/env pwsh
<#
.SYNOPSIS
  Fetches admin/API keys for Foundry, Cosmos, Storage, and Search and writes
  them to a .env file at the repo root.

.DESCRIPTION
  Corp policy in some subs forces MI-only auth (`disableLocalAuth=true`).
  Run `scripts/enable-public-access.ps1` first to flip local auth back on
  before this script — otherwise the "list keys" calls return empty.

  Writes to `.env` at the repo root (adjacent to azure.yaml). This file is
  git-ignored. Existing keys in the file are replaced; other lines are kept.

.PARAMETER ResourceGroup
  Resource group name. Defaults to $env:AZURE_RESOURCE_GROUP or the value from
  `azd env get-values`.

.PARAMETER EnvFile
  Path to the .env file to write. Defaults to <repo-root>/.env.
#>
[CmdletBinding()]
param(
  [string]$ResourceGroup = $env:AZURE_RESOURCE_GROUP,
  [string]$EnvFile
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $EnvFile) { $EnvFile = Join-Path $repoRoot '.env' }

# Resolve RG + read endpoints/names from azd env
$azdValsRaw = azd env get-values 2>$null
$azdVals = @{}
foreach ($line in $azdValsRaw) {
  if ($line -match '^([A-Z_][A-Z0-9_]*)="?([^"]*)"?$') {
    $azdVals[$Matches[1]] = $Matches[2]
  }
}

if (-not $ResourceGroup) { $ResourceGroup = $azdVals['AZURE_RESOURCE_GROUP'] }
if (-not $ResourceGroup) {
  throw "ResourceGroup not provided. Pass -ResourceGroup <name> or set AZURE_RESOURCE_GROUP / run 'azd env select <env>'."
}

Write-Host "==> Fetching keys from '$ResourceGroup' into '$EnvFile'" -ForegroundColor Cyan

# Discover resources in the group
$resources = az resource list -g $ResourceGroup --query "[?type=='Microsoft.CognitiveServices/accounts' || type=='Microsoft.DocumentDB/databaseAccounts' || type=='Microsoft.Storage/storageAccounts' || type=='Microsoft.Search/searchServices'].{name:name,type:type}" -o json | ConvertFrom-Json

$keys = @{}

foreach ($r in $resources) {
  switch ($r.type) {
    'Microsoft.CognitiveServices/accounts' {
      Write-Host "→ Foundry / AI Services: $($r.name)"
      $k = az cognitiveservices account keys list -g $ResourceGroup -n $r.name --query key1 -o tsv
      $keys['FOUNDRY_API_KEY'] = $k
    }
    'Microsoft.DocumentDB/databaseAccounts' {
      Write-Host "→ Cosmos: $($r.name)"
      $k = az cosmosdb keys list -g $ResourceGroup -n $r.name --query primaryMasterKey -o tsv
      $keys['COSMOS_KEY'] = $k
    }
    'Microsoft.Storage/storageAccounts' {
      Write-Host "→ Storage: $($r.name)"
      $k = az storage account keys list -g $ResourceGroup -n $r.name --query "[0].value" -o tsv
      $keys['STORAGE_KEY'] = $k
      $conn = "DefaultEndpointsProtocol=https;AccountName=$($r.name);AccountKey=$k;EndpointSuffix=core.windows.net"
      $keys['STORAGE_CONNECTION_STRING'] = $conn
    }
    'Microsoft.Search/searchServices' {
      Write-Host "→ Search: $($r.name)"
      $k = az search admin-key show -g $ResourceGroup --service-name $r.name --query primaryKey -o tsv
      $keys['AZURE_SEARCH_KEY'] = $k
    }
  }
}

# Also mirror useful non-secret azd env values so apps only need to load .env
$mirror = @(
  'AZURE_SUBSCRIPTION_ID','AZURE_RESOURCE_GROUP','AZURE_TENANT_ID',
  'FOUNDRY_ENDPOINT','FOUNDRY_PROJECT_ENDPOINT',
  'FOUNDRY_PLANNER_DEPLOYMENT','FOUNDRY_WORKER_DEPLOYMENT','FOUNDRY_PROMPT_AGENT_DEPLOYMENT','FOUNDRY_EMBEDDING_DEPLOYMENT',
  'AZURE_SEARCH_ENDPOINT','AZURE_SEARCH_INDEX','AZURE_SEARCH_KNOWLEDGE_BASE','AZURE_SEARCH_KNOWLEDGE_SOURCE','AZURE_OPENAI_ENDPOINT',
  'COSMOS_ENDPOINT','COSMOS_DATABASE',
  'STORAGE_ACCOUNT','STORAGE_CU_CONTAINER','STORAGE_SEED_CONTAINER',
  'APPLICATIONINSIGHTS_CONNECTION_STRING'
)
foreach ($k in $mirror) { if ($azdVals.ContainsKey($k) -and $azdVals[$k]) { $keys[$k] = $azdVals[$k] } }

# Merge with any existing .env, replacing our managed keys
$existing = @()
if (Test-Path $EnvFile) {
  $existing = Get-Content $EnvFile | Where-Object { $_ -notmatch '^\s*#' -and $_ -match '=' }
}
$existingMap = @{}
foreach ($line in $existing) {
  if ($line -match '^([A-Z_][A-Z0-9_]*)=(.*)$') { $existingMap[$Matches[1]] = $Matches[2] }
}
foreach ($k in $keys.Keys) { $existingMap[$k] = $keys[$k] }

$header = @(
  '# Generated by scripts/fetch-keys.ps1 — do not commit.',
  "# Source resource group: $ResourceGroup",
  "# Regenerated: $(Get-Date -Format 'u')",
  ''
)
$body = $existingMap.GetEnumerator() | Sort-Object Name | ForEach-Object { "$($_.Key)=$($_.Value)" }
Set-Content -Path $EnvFile -Value ($header + $body) -Encoding utf8

Write-Host ""
Write-Host "==> Wrote $($existingMap.Count) entries to $EnvFile" -ForegroundColor Cyan
Write-Host "    (this file is git-ignored — do not commit)" -ForegroundColor DarkGray
